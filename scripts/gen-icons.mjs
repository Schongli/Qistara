// Builds src/lib/icon-data.ts (Phosphor, the default, always loaded) and src/lib/icon-packs/<pack>.ts (the other
// packs, loaded only when chosen): only the icons the app uses (scripts/icon-map.json), taken from the
// @iconify-json dev packages so nothing is fetched at run time. Fails on any name a pack doesn't have.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const map = JSON.parse(readFileSync(new URL('./icon-map.json', import.meta.url), 'utf8'))
const PACKS = { phosphor: 'ph', lucide: 'lucide', iconoir: 'iconoir', remix: 'ri', solar: 'solar' }
const sets = Object.fromEntries(Object.values(PACKS).map((p) => [p, require(`@iconify-json/${p}/icons.json`)]))

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()
const missing = []
function get(set, name) {
  const s = sets[set]
  const alias = s.aliases?.[name]
  const icon = s.icons[name] ?? (alias && s.icons[alias.parent])
  if (!icon) {
    const hint = Object.keys(s.icons).filter((k) => k.includes(name.split('-')[0])).slice(0, 8).join(', ')
    missing.push(`${set}:${name}  (try: ${hint})`)
    return null
  }
  return [icon.width ?? alias?.width ?? s.width ?? 16, icon.height ?? alias?.height ?? s.height ?? 16, icon.body]
}

const out = Object.fromEntries(Object.keys(PACKS).map((p) => [p, {}]))
for (const [name, entry] of Object.entries(map)) {
  if (name === '_') continue
  const ph = kebab(name)
  const phosphor = { regular: get('ph', ph), bold: get('ph', `${ph}-bold`), fill: get('ph', `${ph}-fill`) }
  out.phosphor[name] = phosphor
  for (const [pack, set] of Object.entries(PACKS)) {
    if (pack === 'phosphor') continue
    if (entry === 'brand') continue // the logo is the logo: Phosphor's, whatever the pack
    const [regular, filled] = entry[set].split('|')
    const r = get(set, regular)
    out[pack][name] = { regular: r, fill: filled === '*' ? r && [...r, 1] : filled ? get(set, filled) : null }
  }
}
if (missing.length) {
  console.error(`Not in the icon packs:\n  ${missing.join('\n  ')}`)
  process.exit(1)
}
const head = `// Generated by scripts/gen-icons.mjs from scripts/icon-map.json: do not edit.\n`
writeFileSync(
  new URL('../src/lib/icon-data.ts', import.meta.url),
  head +
    `// [width, height, svg body, fill with CSS?] per icon, pack and weight. Licences: Phosphor MIT, Lucide ISC, Iconoir MIT,\n` +
    `// Remix Icon Apache-2.0, Solar CC BY 4.0 (480 Design). The other packs are in icon-packs/, loaded when chosen.\n` +
    `export type Glyph = [number, number, string, 1?]\n` +
    `export type Weights = { regular: Glyph | null; bold?: Glyph | null; fill?: Glyph | null }\n` +
    `export const PHOSPHOR: Record<string, Weights> = ${JSON.stringify(out.phosphor)}\n`,
)
mkdirSync(new URL('../src/lib/icon-packs/', import.meta.url), { recursive: true })
for (const pack of Object.keys(PACKS).filter((p) => p !== 'phosphor')) {
  writeFileSync(
    new URL(`../src/lib/icon-packs/${pack}.ts`, import.meta.url),
    head + `import type { Weights } from '../icon-data'\nexport const PACK: Record<string, Weights> = ${JSON.stringify(out[pack])}\n`,
  )
}
console.log('icon-data.ts written:', Object.keys(map).length - 1, 'icons')
